// Focused browser regressions: lifecycle, mobile threshold controls, live context loss.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PW_PATH || 'playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const url = 'file://' + root + '/dist/index.html?e2e';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
let failures = 0;
const check = (name, ok, details = '') => { console.log(`${ok ? 'PASS' : 'FAIL'} ${name} ${details}`); if (!ok) failures++; };
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(url);
await page.getByRole('button', { name: 'Начать путешествие' }).click();
await page.waitForFunction(() => window.__horeb && window.__horeb.state(), null, { timeout: 60000 });
await page.evaluate(() => { const w = window.__horeb.world; w.teleportTo(0, -351.7); w.yaw = 0; });
await page.waitForTimeout(700);
const elements = await page.evaluate(() => {
  const gate = document.querySelector('.gate');
  const stick = document.querySelector('.touch-none');
  const action = [...document.querySelectorAll('button')].find((b) => b.textContent === 'Действие');
  const rect = (e) => { const r = e.getBoundingClientRect(); return { left: r.left, top: r.top, right: r.right, bottom: r.bottom }; };
  return { gate: gate && rect(gate), stick: stick && rect(stick), action: action && rect(action) };
});
const overlap = (a, b) => a && b && Math.max(0, Math.min(a.right, b.right) - Math.max(a.left, b.left)) * Math.max(0, Math.min(a.bottom, b.bottom) - Math.max(a.top, b.top));
check('touch controls do not overlap Exodus 3:5', overlap(elements.gate, elements.stick) === 0 && overlap(elements.gate, elements.action) === 0, JSON.stringify(elements));
await page.screenshot({ path: root + '/audit/screens/13-mobile-threshold.png' });
await page.setViewportSize({ width: 320, height: 640 });
const small = await page.evaluate(() => {
  const a = document.querySelector('.gate').getBoundingClientRect();
  const nav = document.querySelector('nav[aria-label="Управление экспозицией"]').getBoundingClientRect();
  const stick = document.querySelector('.touch-none').getBoundingClientRect();
  return { gate: { left: a.left, right: a.right, top: a.top, bottom: a.bottom }, nav: { left: nav.left, right: nav.right, top: nav.top, bottom: nav.bottom }, stick: { left: stick.left, right: stick.right, top: stick.top, bottom: stick.bottom } };
});
check('320px: Exodus notice clears navigation and joystick', overlap(small.gate, small.nav) === 0 && overlap(small.gate, small.stick) === 0, JSON.stringify(small));
await page.screenshot({ path: root + '/audit/screens/14-mobile-threshold-320.png' });
await page.getByRole('button', { name: /Снять обувь/ }).click();
await page.waitForTimeout(3000);
check('touch sandal action advances state', (await page.evaluate(() => window.__horeb.state())).shoes === 'unshod');
await page.getByRole('button', { name: 'Меню' }).click();
await page.getByRole('button', { name: 'Выйти из прогулки' }).click();
check('world exit returns to intro', await page.getByRole('button', { name: 'Начать путешествие' }).isVisible());
await page.getByRole('button', { name: 'Начать путешествие' }).click();
await page.waitForFunction(() => window.__horeb && window.__horeb.world && !window.__horeb.world.disposed, null, { timeout: 60000 });
check('re-entry resets shoes fail closed', (await page.evaluate(() => window.__horeb.state())).shoes === 'shod');
check('re-entry does not report runtime errors', errors.length === 0, errors.join(' | '));
await page.close();
const corrupt = await browser.newPage();
await corrupt.goto(url);
await corrupt.evaluate(() => {
  localStorage.setItem('imena-horeb.progress.v1', JSON.stringify({ visited: null, last: { x: 'NaN', z: -366 } }));
  localStorage.setItem('imena-horeb.settings.v1', JSON.stringify({ quality: 'ultra', exposure: -100, particles: 'false' }));
});
await corrupt.reload();
await corrupt.getByRole('button', { name: 'Начать путешествие' }).click();
await corrupt.waitForFunction(() => window.__horeb && window.__horeb.state(), null, { timeout: 60000 });
check('corrupted local storage is sanitized without crash', await corrupt.getByText('Зона 0', { exact: false }).first().isVisible());
const exposure = await corrupt.evaluate(() => window.__horeb.world.settings.exposure);
check('corrupted brightness cannot escape valid range', exposure >= 0.6 && exposure <= 2, `exposure=${exposure}`);
await corrupt.close();
await browser.close();
console.log(`${failures} failures`);
process.exit(failures ? 1 : 0);