const assert = require('node:assert/strict');
const ts = require('typescript');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const source = fs.readFileSync(path.join(__dirname, '../src/progression/engine.ts'), 'utf8');
  const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
  const m = await import('data:text/javascript;base64,' + Buffer.from(outputText).toString('base64'));
  let s = structuredClone(m.EMPTY_PROGRESS);
  const at = '2026-10-08T12:00:00Z';
  const event = { action: 'article_finished', artifactId: 'article-a', completed: true, timestamp: at };
  let res = m.record(s, event); assert.equal(res.ok, true); s = res.state;
  assert.equal(m.summarize(s).xp, 20);
  assert.equal(m.record(s, event).ok, false, 'no farming duplicates');
  assert.equal(m.record(s, { action:'quiz_mastered', artifactId: 'quiz-a', timestamp: at, masteryPercent: 100, feedbackReviewed:false }).ok, false);
  assert.equal(m.record(s, { action:'quiz_mastered', artifactId: 'quiz-a', timestamp: at, masteryPercent: 74, feedbackReviewed:true }).ok, false);
  assert.equal(m.record(s, { action:'note_with_source', artifactId: 'article-a', timestamp: at, hasOwnNote:true }).ok, false);
  assert.equal(m.record(s, { action:'collection_curated', artifactId: 'coll-a', timestamp: at, itemCount:2 }).ok, false);
  assert.equal(m.record(s, { action:'path_completed', artifactId: 'path-a', timestamp: at, pathStages:2, completed:true }).ok, false);
  assert.equal(m.record(s, { action:'review_completed', artifactId: 'article-a', timestamp: at, checkpoint:1 }).ok, false);
  res = m.record(s, { action:'review_completed', artifactId: 'article-a', timestamp:'2026-10-09T12:00:00Z', checkpoint:1 });
  assert.equal(res.ok, true);s=res.state;
  assert.equal(m.record(s, { action:'review_completed', artifactId: 'article-a', timestamp:'2026-10-15T12:00:00Z', checkpoint:1 }).ok, false);
  assert.equal(m.summarize(s).xp, 45);
  for (let i=0;i<7;i++) {let rr=m.record(s, {action:'path_completed',artifactId:'path-'+i,timestamp:at,completed:true,pathStages:3});assert.equal(rr.ok,true);s=rr.state;}
  assert.equal(m.summarize(s).level, 5);
  assert.equal(m.summarize(s).tokens, 11);
  const bought=m.buyDecor(s, 'lamp'); assert.equal(bought.ok, true); assert.equal(m.summarize(bought.state).tokens, 10);
  assert.equal(m.buyDecor(bought.state, 'lamp').ok,false);
  assert.equal(m.buyDecor(s,'map').ok,false, 'level gated');
  assert.equal(m.achievements(s).find(a => a.id === 'first-read').earned, true);
  assert.equal(m.achievements(s).find(a => a.id === 'first-source').earned, false);
  assert.equal(m.achievements(s).find(a => a.id === 'path').earned, true);
  assert.equal(m.parseProgress('bad JSON').events.length, 0);
  assert.equal(m.parseProgress(JSON.stringify(bought.state)).events.length,bought.state.events.length);
  assert.equal(m.parseProgress(JSON.stringify({...bought.state, events:[...bought.state.events,{key:'bad',action:'path_completed', artifactId:'p', timestamp:at, xp:9999}]})).events.length,bought.state.events.length);
  assert.equal(m.record(s, {action:'article_finished',artifactId:'future',timestamp:'2099-01-01T00:00:00Z',completed:true}).ok,false,'future event is rejected on write');
  const intact = m.inspectProgress(JSON.stringify(bought.state));
  assert.equal(intact.ok, true);
  assert.equal(intact.state.events.length, bought.state.events.length);
  assert.equal(m.inspectProgress('bad-json').ok, false);
  const forged = {...bought.state, events:[...bought.state.events, {key:'path_completed:evil', action:'path_completed',artifactId:'evil',timestamp:at,xp:999999}]};
  assert.equal(m.inspectProgress(JSON.stringify(forged)).ok, false, 'forged XP fails closed');
  const duplicate = {...bought.state, events:[...bought.state.events, bought.state.events[0]]};
  assert.equal(m.inspectProgress(JSON.stringify(duplicate)).ok,false, 'duplicate ledger fails closed');
  const impossiblePurchase={...m.EMPTY_PROGRESS,purchases:['lamp']};
  assert.equal(m.inspectProgress(JSON.stringify(impossiblePurchase)).ok,false, 'wallet overspend is rejected');
  const futureEvent={...m.EMPTY_PROGRESS,events:[{key:'article_finished:future',action:'article_finished',artifactId:'future',timestamp:'2099-01-01T00:00:00Z',xp:20}]};
  assert.equal(m.inspectProgress(JSON.stringify(futureEvent)).ok,false);
  const invalidStamp = {...m.EMPTY_PROGRESS,events:[{key:'article_finished:fake',action:'article_finished',artifactId:'fake',timestamp:'2026-02-30T01:01:01.000Z',xp:20}],purchases:[]};
  assert.equal(m.inspectProgress(JSON.stringify(invalidStamp)).ok,false,'impossible calendar day');
  const wrongFormat={...invalidStamp,events:[{...invalidStamp.events[0],timestamp:'2026-11-08T16:00:00+00:00'}]};
  assert.equal(m.inspectProgress(JSON.stringify(wrongFormat)).ok,false,'non canonical UTC format');
  const today=new Date().toISOString();
  let dated=m.record(m.EMPTY_PROGRESS,{action:'article_finished',artifactId:'doc',timestamp:today,completed:true});
  assert.equal(dated.ok,true);
  assert.equal(m.record(dated.state,{action:'article_finished',artifactId:'extra',timestamp:'2026/11/08 16:00:00',completed:true}).ok,false,'reject permissive date syntax');
  console.log('PASS: progression rules and achievement invariant checks incl. duplicates, mastery, delayed review, level boundaries, wallet, parsing');
})().catch(e=>{ console.error(e); process.exitCode=1; });
